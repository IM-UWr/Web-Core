// Wersja angielska ma te same adresy z przedrostkiem /en (np. /en/aktualnosci).
export function jezykZeSciezki(pathname: string): Lang {
  return /^\/en(\/|$)/.test(pathname) ? 'en' : 'pl';
}

export function wJezyku(path: string, lang: Lang): string {
  // pliki (/pliki/…) i kanały (.ics, .xml, .json) nie mają wersji językowych
  if (lang === 'pl' || /^(https?:|mailto:|tel:|#)/.test(path) || /^\/pliki\//.test(path) || /\.(ics|xml|json)$/.test(path)) return path;
  if (/^\/en(\/|$)/.test(path)) return path;
  return path === '/' ? '/en/' : '/en' + (path.startsWith('/') ? path : '/' + path);
}

export function drugiJezyk(pathname: string): string {
  if (jezykZeSciezki(pathname) === 'en') return pathname.replace(/^\/en/, '') || '/';
  return wJezyku(pathname, 'en');
}

// Pole w wybranym języku: wybierz(obj, 'etykieta', 'en') → obj.etykieta_en ?? obj.etykieta
export function wybierz<T extends Record<string, any>>(obj: T, pole: string, lang: Lang): string {
  if (lang === 'en' && obj[pole + '_en']) return obj[pole + '_en'];
  return obj[pole] ?? '';
}
